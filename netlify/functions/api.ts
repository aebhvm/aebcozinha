async function ensureColumn(table: string, column: string, sql: string) {
  const columns = await getDb().execute({
    sql: `select 1 from information_schema.columns where table_schema = 'public' and table_name = ? and column_name = ?`,
    args: [table, column],
  })
  const exists = columns.rows.length > 0

  if (!exists) {
    try {
      await getDb().execute(sql)
    } catch (error) {
      const message = error instanceof Error ? error.message.toLowerCase() : ''
      if (!message.includes('duplicate column')) throw error
    }
  }
}

